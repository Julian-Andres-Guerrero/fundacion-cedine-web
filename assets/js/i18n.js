document.addEventListener('DOMContentLoaded', () => {
  let currentLang = localStorage.getItem('cedine_lang') || 'es';

  const langToggleDesktop = document.getElementById('lang-toggle');
  const langToggleMobile = document.getElementById('lang-toggle-mobile');
  const currentLangLabel = document.getElementById('current-lang');

  function applyLanguage(lang) {
    document.documentElement.lang = lang;
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });

    if (currentLangLabel) currentLangLabel.textContent = lang.toUpperCase();
    if (langToggleMobile) langToggleMobile.textContent = lang.toUpperCase();
    localStorage.setItem('cedine_lang', lang);
  }

  function toggleLanguage() {
    currentLang = currentLang === 'es' ? 'en' : 'es';
    applyLanguage(currentLang);
  }

  if (langToggleDesktop) langToggleDesktop.addEventListener('click', toggleLanguage);
  if (langToggleMobile) langToggleMobile.addEventListener('click', toggleLanguage);

  applyLanguage(currentLang);
});